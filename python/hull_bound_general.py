"""
General Spectral Hull Bound Checker.

Checks whether the spectral hull bound applies to any S-box.
The hull bound P_hull <= 2^{-n/2} holds if and only if the S-box
differential distribution has vanishing Fourier coefficients for all
non-trivial characters.

This module is parameterized over the S-box and can be used to check
the hull bound for any SPN cipher.

Mano H. | 2026
"""
from __future__ import annotations

import math
from typing import Optional


def build_ddt(sbox: list[int]) -> list[list[int]]:
    """Build the Differential Distribution Table for any S-box."""
    n = len(sbox)
    ddt = [[0] * n for _ in range(n)]
    for dx in range(n):
        for x in range(n):
            dy = sbox[x] ^ sbox[x ^ dx]
            ddt[dx][dy] += 1
    return ddt


def popcount(x: int) -> int:
    """Count the number of set bits in x."""
    return bin(x).count('1')


def compute_fourier_coefficients(sbox: list[int]) -> dict[int, float]:
    """
    Compute the 1D Fourier coefficients of the S-box differential distribution.

    hat_S(chi) = (1/n^2) * sum_{dx,dy} DDT[dx][dy] * (-1)^{popcount(chi & dy)}

    where n is the S-box size.

    Returns a dictionary mapping each character chi to its Fourier coefficient.
    """
    n = len(sbox)
    ddt = build_ddt(sbox)
    fourier_coeffs = {}
    for chi in range(n):
        total = sum(
            ddt[dx][dy] * ((-1) ** popcount(chi & dy))
            for dx in range(n)
            for dy in range(n)
        )
        fourier_coeffs[chi] = total / (n * n)
    return fourier_coeffs


def check_fourier_vanishing(sbox: list[int]) -> dict:
    """
    Check if the Fourier coefficients vanish for all non-trivial characters.

    Returns a dictionary with:
    - 'applies': bool - whether the hull bound applies
    - 'coefficients': dict - Fourier coefficients for each character
    - 'max_nontrivial': float - max |coefficient| for non-trivial characters
    - 'normalization': float - coefficient for chi=0 (should be 1)
    """
    n = len(sbox)
    fourier_coeffs = compute_fourier_coefficients(sbox)

    # Check normalization (chi=0 should give 1)
    normalization = fourier_coeffs[0]

    # Check vanishing for non-trivial characters
    max_nontrivial = 0
    for chi in range(1, n):
        coeff = abs(fourier_coeffs[chi])
        if coeff > max_nontrivial:
            max_nontrivial = coeff

    # The hull bound applies if all non-trivial coefficients are (near) zero
    applies = max_nontrivial < 1e-10

    return {
        'applies': applies,
        'coefficients': fourier_coeffs,
        'max_nontrivial': max_nontrivial,
        'normalization': normalization,
        'sbox_size': n,
    }


def compute_hull_bound(sbox_size: int, block_size: int) -> Optional[float]:
    """
    Compute the hull bound if the Fourier vanishing property holds.

    Returns 2^{-block_size/2} if the bound applies, None otherwise.
    """
    # The bound is 2^{-block_size/2} for an SPN with the given block size
    return 2.0 ** (-block_size / 2)


def analyze_sbox(sbox: list[int], name: str = "Unknown") -> dict:
    """
    Perform a complete analysis of an S-box for the spectral hull bound.

    Returns a dictionary with the analysis results.
    """
    n = len(sbox)
    result = check_fourier_vanishing(sbox)
    result['name'] = name
    result['sbox'] = sbox

    if result['applies']:
        result['bound'] = 2.0 ** (-n / 2)  # For a single S-box layer
        result['log2_bound'] = -n / 2
    else:
        result['bound'] = None
        result['log2_bound'] = None

    return result


